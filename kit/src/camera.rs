//! 何が映っているか。
//!
//! 実装は `home::io::camera`。遊びには**縮めて左右を反転した絵**だけを
//! 渡す。何が動いたか・どこを触ったかを決めるのは遊びの側で、`Listener`
//! が文字だけ渡して解釈を遊びに任せるのと同じ分け方にしてある。絵は
//! 画素の並びでしかないので、偽の絵を組めば装置なしで試せる。
//!
//! **映像は保存も送信もしない。** 子どもが映るため。遊びも、受け取った
//! 絵を画面に出す以外に使わないこと。

use anyhow::Result;

use crate::Image;

/// 渡す絵の大きさ。キャンバス（16:9）と同じ縦横比で、その 1/4。
///
/// 遊びはこの絵を `Scene::image` にそのまま敷ける。カメラの縦横比が
/// 違えば `home` が真ん中を切り出して合わせる。
pub const CAMERA_WIDTH: usize = 320;
pub const CAMERA_HEIGHT: usize = 180;

pub trait Camera {
    /// 次の1枚を待って返す。**左右は反転済み**（鏡）なので、子どもが
    /// 右手を上げると絵の右側が動く。大きさは常に
    /// `CAMERA_WIDTH` × `CAMERA_HEIGHT`。
    ///
    /// 新しい絵が来るまで待つので、呼ぶ側の1周の速さはカメラで決まる
    /// （毎秒30枚くらい）。休んでいたら、ここで撮り始める。
    fn frame(&mut self) -> Result<Image>;

    /// 撮るのをやめる。**カメラの横のランプが消える。** 遊び終えたら呼ぶ。
    /// 次の `frame` で撮り直す。
    fn rest(&mut self);
}
