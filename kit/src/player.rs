//! 素材をどう鳴らすか。
//!
//! 実装は `home::io::player::Speakers`（rodio）だけで、選択肢があるわけでは
//! ない。それでもトレイトにしてあるのは、**これが具象だと進行を一切テスト
//! できない**ため。遊びに貸す4つのうち他の3つはトレイトなので、ここが実の
//! デバイスを開く限り、遊びを組み立てられない。
//!
//! 長さ0を返す偽物を置けば、鳴らした素材の並びをそのまま検査できて、
//! しかも待ち時間が消える。
//!
//! **素材は「どの遊びの・どの名前」で指す。** 何があるかは遊びごとに
//! 違うので、型で縛るのは遊びの側（`donna_iro::Cue` など）の仕事。ここに
//! 届くのは名前だけで、在処（`games/<game>/assets/<name>.wav`）を決めるのは
//! `home`。遊びの名前まで運ぶのは、別の遊びが同じ名前（`intro` など）を
//! 持てるようにするため。

use anyhow::Result;

/// 鳴らす素材。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Sound {
    /// どの遊びのものか。`Game::id` と同じ。
    pub game: &'static str,
    /// 素材の名前。拡張子は付けない。
    pub name: &'static str,
}

/// 素材の長さ。
pub struct Timing {
    /// 末尾の無音まで含めた全長。
    pub total: std::time::Duration,
    /// 音が鳴り止むまで。
    pub audible: std::time::Duration,
}

/// 素材を鳴らすもの。
///
/// `Send` は要求しない。rodio の出力ストリームが `!Send` で、ワーカー
/// スレッドの中で開くことになっているため。
///
/// **待つのはここではない。** 以前は `play`（鳴らし終わるまで待つ）と
/// `play_until_quiet` を持っていたが、どちらも中身は
/// `sleep(begin().total)` で、待っている間に外を見る余地が無かった。
/// 「戻る」で途中から抜けられるようにするには待ちを遊びの側に置くしかなく、
/// そうすると**タイミングの政策が遊びに集まる**ので層の建前にも合う。
/// 装置に残るのは「始める」と「止める」だけ。
pub trait Player {
    /// **鳴らし始めて長さだけ返す。待たない。**
    ///
    /// 前に `begin` したものは止めて置き換える。歌や曲はこちら。
    fn begin(&self, sound: Sound) -> Result<Timing>;

    /// 効果音を重ねる。**`begin` したものは止めない。**
    ///
    /// 口は `begin` とこれの2本だけ。前の効果音はこれで置き換わるので、
    /// 立て続けに鳴らしても重なり過ぎない（風船を続けて割ったとき）。
    fn effect(&self, sound: Sound) -> Result<()>;

    /// 鳴っているものを止める。`begin` も `effect` も両方。
    ///
    /// **画面だけ切り替えて歌が流れ続ける、を防ぐためにある。**
    /// 何も鳴っていなければ何もしない。
    fn silence(&self);
}
